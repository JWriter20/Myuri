"""Generate myuri's embedded English bigram table (JS + Python).

Source: english_bigrams.txt from John Burkardt's NGRAMS dataset,
https://people.sc.fsu.edu/~jburkardt/datasets/ngrams/ngrams.html (GNU LGPL).

The 676 counts are stored as one byte each, in a-z x a-z order:
byte = round(-20 * log10(share)), clamped to 0..255, where share is the
bigram's fraction of all bigrams. Decoding gives log10(share) to +-0.025.

usage: python3 scripts/gen_bigrams.py path/to/english_bigrams.txt
"""
import base64
import math
import os
import sys

src = sys.argv[1]
counts = {}
for line in open(src):
    key, value = line.split()
    counts[key.lower()] = int(value)
total = sum(counts.values())
letters = 'abcdefghijklmnopqrstuvwxyz'
table = bytearray()
for a in letters:
    for b in letters:
        n = counts.get(a + b, 0)
        q = 255 if n == 0 else min(255, max(0, round(-20 * math.log10(n / total))))
        table.append(q)
assert len(table) == 676
b64 = base64.b64encode(bytes(table)).decode()
# Frequency-weighted mean log10 share: the value for "average English", so a
# pair at this frequency gets no speed-up or slow-down.
mean = sum(n / total * (-table[letters.index(k[0]) * 26 + letters.index(k[1])] / 20) for k, n in counts.items())

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
header = (
    'English bigram frequencies, generated by scripts/gen_bigrams.py from\n'
    "english_bigrams.txt in John Burkardt's NGRAMS dataset\n"
    '(https://people.sc.fsu.edu/~jburkardt/datasets/ngrams/ngrams.html, GNU LGPL).\n'
    'Do not edit by hand.\n'
)
with open(os.path.join(root, 'js/src/typing/bigrams.ts'), 'w') as f:
    f.write('/**\n' + ''.join(' * ' + l + '\n' for l in header.splitlines()) + ' */\n\n')
    f.write('/** 676 bytes, a-z x a-z: byte = round(-20 * log10(share of all bigrams)). */\n')
    f.write(f"export const BIGRAM_TABLE_B64 =\n  '{b64}'\n\n")
    f.write('/** Frequency-weighted mean log10 share (the "average English pair"). */\n')
    f.write(f'export const BIGRAM_MEAN_LOG10 = {mean:.4f}\n')
with open(os.path.join(root, 'python/src/myuri/typing_engine/bigrams.py'), 'w') as f:
    f.write('"""' + header + '"""\n\n')
    f.write('# 676 bytes, a-z x a-z: byte = round(-20 * log10(share of all bigrams)).\n')
    chunks = [b64[i:i + 76] for i in range(0, len(b64), 76)]
    f.write('BIGRAM_TABLE_B64 = (\n' + ''.join(f'    "{c}"\n' for c in chunks) + ')\n\n')
    f.write('# Frequency-weighted mean log10 share (the "average English pair").\n')
    f.write(f'BIGRAM_MEAN_LOG10 = {mean:.4f}\n')
print('mean', mean, 'zero pairs', sum(1 for x in table if x == 255))
